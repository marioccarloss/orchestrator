/**
 * Portable Atlas: a local-only context pack that ANY agent can use, plus a
 * managed pointer block in the agent instruction files of each repository.
 *
 *   <workspace>/.aicontext/atlas/MAP.md     compact map (stack, commands, folders, key symbols)
 *   <workspace>/.aicontext/atlas/MEMORY.md  project decisions from Engram (best-effort)
 *   <workspace>/.aicontext/atlas/AGENTS.md  rules (written by `mr atlas init|rules`)
 *
 * The pack never leaves the machine: `.aicontext/` and any AGENTS.md created by
 * mr are added to `.git/info/exclude` (local, untracked ignore), never to `.gitignore`.
 */

export const ATLAS_BLOCK_START = "<!-- mr-atlas:start -->";
export const ATLAS_BLOCK_END = "<!-- mr-atlas:end -->";
export const MAP_CHAR_BUDGET = 16_000;

/**
 * Instruction files that other agents read. AGENTS.md and CLAUDE.md are created when missing
 * (Claude Code reads CLAUDE.md, not AGENTS.md, so a created CLAUDE.md just imports @AGENTS.md);
 * the rest are only updated when present.
 */
export const POINTER_TARGETS = [
  { file: "AGENTS.md", create: true },
  { file: "CLAUDE.md", create: true },
  { file: "GEMINI.md", create: false },
  { file: ".github/copilot-instructions.md", create: false },
] as const;

export function atlasPackRoot(workspace: Pick<WorkspaceProfile, "contextRoot">): string {
  return join(workspace.contextRoot, "atlas");
}

function gitHead(root: string): string | undefined {
  const result = runCommand("git", ["-C", root, "rev-parse", "--short", "HEAD"]);
  return result.ok ? result.stdout.trim() : undefined;
}

function connectivity(node: AtlasNode): number {
  return node.dependents.length * 2 + node.dependencies.length;
}

const SIGNIFICANT_KINDS = new Set<AtlasNode["kind"]>([
  "component", "hook", "service", "class", "function", "route", "entity", "contract", "federation-contract", "server-action", "slice", "query-key", "interface", "type",
]);

function topDirectories(graph: AtlasGraph, depth = 2): readonly { readonly dir: string; readonly files: number; readonly kinds: string }[] {
  const byDir = new Map<string, { files: Set<string>; kinds: Map<string, number> }>();
  for (const file of graph.files) {
    if (file.parseStatus === "unsupported") continue;
    const parts = file.path.split("/");
    const dir = parts.length <= 1 ? "." : parts.slice(0, Math.min(depth, parts.length - 1)).join("/");
    const entry = byDir.get(dir) ?? { files: new Set<string>(), kinds: new Map<string, number>() };
    entry.files.add(file.path);
    byDir.set(dir, entry);
  }
  for (const node of graph.nodes) {
    const parts = node.filePath.split("/");
    const dir = parts.length <= 1 ? "." : parts.slice(0, Math.min(depth, parts.length - 1)).join("/");
    const entry = byDir.get(dir);
    if (entry !== undefined) entry.kinds.set(node.kind, (entry.kinds.get(node.kind) ?? 0) + 1);
  }
  return [...byDir.entries()]
    .map(([dir, entry]) => ({
      dir,
      files: entry.files.size,
      kinds: [...entry.kinds.entries()].sort((left, right) => right[1] - left[1]).slice(0, 3).map(([kind, count]) => `${kind}×${String(count)}`).join(", "),
    }))
    .sort((left, right) => left.dir.localeCompare(right.dir))
    .slice(0, 60);
}

function oneLine(text: string, max: number): string {
  const flat = text.replace(/\s+/gu, " ").trim();
  return flat.length <= max ? flat : `${flat.slice(0, max - 1)}…`;
}

export interface AtlasMapInput {
  readonly workspace: Pick<WorkspaceProfile, "id" | "name" | "root">;
  readonly graph: AtlasGraph;
  readonly profiles: readonly RepositoryProfile[];
  readonly hasRules: boolean;
  readonly hasMemory: boolean;
  readonly head?: string;
  readonly now?: string;
}

/** Deterministic, bounded markdown map. Most connected symbols first; truncated to MAP_CHAR_BUDGET. */
export function renderAtlasMap(input: AtlasMapInput): string {
  const { graph } = input;
  const lines: string[] = [
    `# Atlas map — ${input.workspace.name}`,
    "",
    `Indexed ${input.now ?? graph.generatedAt}${input.head === undefined ? "" : ` at commit ${input.head}`}: ${String(graph.stats.totalFiles)} files, ${String(graph.stats.totalNodes)} symbols, ${String(graph.stats.totalEdges)} edges.`,
    "Generated by `mr atlas index`. Local to this machine; never commit it.",
    "",
    "## How to use this map",
    "1. Read this file first; open source files only at the `file:line` ranges you need.",
    "2. Ask the graph before searching: `mr atlas query <Symbol> info|deps|dependents|impact|slice|tests` (run it from the workspace).",
    `3. Conventions and rules: ${input.hasRules ? "`AGENTS.md` next to this file." : "not generated yet (`mr atlas init`)."}`,
    `4. Past decisions: ${input.hasMemory ? "`MEMORY.md` next to this file." : "none recorded."}`,
    "5. If the commit above is older than the code you are changing, run `mr atlas index` first.",
    "",
  ];
  if (input.profiles.length > 0) {
    lines.push("## Repositories", "", "| repo | kind | stack | layout | test | lint | typecheck | critical areas |", "|---|---|---|---|---|---|---|---|");
    for (const profile of input.profiles) {
      const stack = [...profile.stack.languages, ...profile.stack.frameworks].slice(0, 5).join(", ");
      lines.push(`| ${profile.repo} (${profile.root}) | ${profile.kind} | ${stack} | ${profile.layout.style} | ${profile.commands.test ?? "—"} | ${profile.commands.lint ?? "—"} | ${profile.commands.typecheck ?? "—"} | ${profile.criticalAreas.join(", ") || "—"} |`);
    }
    lines.push("");
  }
  lines.push("## Folders", "", "| folder | files | main symbols |", "|---|---:|---|");
  for (const row of topDirectories(graph)) lines.push(`| ${row.dir} | ${String(row.files)} | ${row.kinds || "—"} |`);
  lines.push("");

  const entryKinds = new Set<AtlasNode["kind"]>(["route", "server-action", "federation-contract", "contract"]);
  const entries = graph.nodes.filter((node) => entryKinds.has(node.kind)).slice(0, 40);
  if (entries.length > 0) {
    lines.push("## Entry points and contracts", "");
    for (const node of entries) lines.push(`- ${node.kind} \`${node.name}\` — ${node.filePath}:${String(node.line)}`);
    lines.push("");
  }

  lines.push("## Key symbols (most connected first)", "");
  const header = lines.join("\n");
  const symbolLines: string[] = [];
  let used = header.length;
  const ranked = graph.nodes
    .filter((node) => SIGNIFICANT_KINDS.has(node.kind))
    .sort((left, right) => connectivity(right) - connectivity(left) || left.filePath.localeCompare(right.filePath) || left.line - right.line);
  let omitted = 0;
  for (const node of ranked) {
    const signature = node.signature === undefined ? "" : ` — \`${oneLine(node.signature, 110)}\``;
    const line = `- ${node.kind} \`${node.name}\` ${node.filePath}:${String(node.line)} (←${String(node.dependents.length)} →${String(node.dependencies.length)})${signature}`;
    if (used + line.length + 1 > MAP_CHAR_BUDGET - 200) {
      omitted += 1;
      continue;
    }
    symbolLines.push(line);
    used += line.length + 1;
  }
  const footer = omitted === 0 ? [] : ["", `…${String(omitted)} more symbols: use \`mr atlas query\`.`];
  return `${[header, ...symbolLines, ...footer].join("\n")}\n`;
}

export function renderAtlasPointer(packRelative: string): string {
  return [
    ATLAS_BLOCK_START,
    "## Project context (Atlas)",
    "",
    `Before exploring this repository, read \`${packRelative}/MAP.md\` (stack, commands, folders, key symbols with file:line).`,
    `Rules: \`${packRelative}/AGENTS.md\` · past decisions: \`${packRelative}/MEMORY.md\` (when present).`,
    "Use `mr atlas query <Symbol> deps|dependents|impact|slice|tests` instead of reading files broadly; then read only the cited ranges.",
    "If these files are missing, ignore this section (the pack is local to the developer's machine).",
    ATLAS_BLOCK_END,
  ].join("\n");
}

/** Managed CLAUDE.md block: Claude Code resolves `@AGENTS.md` as an import, so the pointer lives in one place. */
export function renderClaudeImport(): string {
  return [ATLAS_BLOCK_START, "@AGENTS.md", ATLAS_BLOCK_END].join("\n");
}

function importsAgentsOutsideBlock(content: string): boolean {
  return /^\s*@AGENTS\.md\s*$/mu.test(removeManagedBlock(content));
}

/** Inserts or replaces only the managed block; everything outside the markers is preserved byte for byte. */
export function upsertManagedBlock(content: string, block: string): string {
  const start = content.indexOf(ATLAS_BLOCK_START);
  const end = content.indexOf(ATLAS_BLOCK_END);
  if (start !== -1 && end > start) {
    return `${content.slice(0, start)}${block}${content.slice(end + ATLAS_BLOCK_END.length)}`;
  }
  if (content.trim().length === 0) return `${block}\n`;
  return `${content.replace(/\s*$/u, "")}\n\n${block}\n`;
}

export function removeManagedBlock(content: string): string {
  const start = content.indexOf(ATLAS_BLOCK_START);
  const end = content.indexOf(ATLAS_BLOCK_END);
  if (start === -1 || end < start) return content;
  return `${content.slice(0, start).replace(/\s*$/u, "")}${content.slice(end + ATLAS_BLOCK_END.length).replace(/^\s*/u, content.slice(0, start).trim().length === 0 ? "" : "\n")}`.replace(/\s*$/u, "\n");
}

/** Adds patterns to `.git/info/exclude` (local-only ignore). Returns false outside git. */
export async function excludeLocally(repoRoot: string, patterns: readonly string[]): Promise<boolean> {
  const result = runCommand("git", ["-C", repoRoot, "rev-parse", "--git-path", "info/exclude"]);
  if (!result.ok) return false;
  const raw = result.stdout.trim();
  const excludePath = isAbsolute(raw) ? raw : join(repoRoot, raw);
  const current = await readFile(excludePath, "utf8").catch(() => "");
  const lines = new Set(current.split(/\r?\n/u).map((line) => line.trim()));
  const missing = patterns.filter((pattern) => !lines.has(pattern));
  if (missing.length === 0) return true;
  await mkdir(dirname(excludePath), { recursive: true });
  await appendFile(excludePath, `${current.length === 0 || current.endsWith("\n") ? "" : "\n"}# mr-orchestrator local Atlas (never commit)\n${missing.join("\n")}\n`, "utf8");
  return true;
}

function isTracked(repoRoot: string, file: string): boolean {
  return runCommand("git", ["-C", repoRoot, "ls-files", "--error-unmatch", file]).ok;
}

export interface PointerChange {
  readonly path: string;
  readonly action: "created" | "updated" | "unchanged";
  readonly tracked: boolean;
}

/** Writes the pointer block into each repository's agent files (AGENTS.md is created when missing). */
export async function linkAtlasPointers(workspace: Pick<WorkspaceProfile, "root" | "contextRoot">, repoRoots: readonly string[]): Promise<readonly PointerChange[]> {
  const changes: PointerChange[] = [];
  const roots = repoRoots.length === 0 ? [workspace.root] : [...new Set(repoRoots)];
  for (const repoRoot of roots) {
    const packRelative = relative(repoRoot, atlasPackRoot(workspace)) || ".";
    // Inside the workspace a relative path keeps the block portable; far away, an absolute path is clearer.
    const upLevels = packRelative.split("/").filter((part) => part === "..").length;
    const block = renderAtlasPointer(upLevels > 3 ? atlasPackRoot(workspace) : packRelative);
    const createdHere: string[] = [];
    for (const target of POINTER_TARGETS) {
      const path = join(repoRoot, target.file);
      const exists = existsSync(path);
      if (!exists && !target.create) continue;
      const previous = exists ? await readFile(path, "utf8") : "";
      const claude = target.file === "CLAUDE.md";
      // A CLAUDE.md that already imports @AGENTS.md sees the AGENTS.md pointer; do not duplicate it.
      const next = claude && exists && importsAgentsOutsideBlock(previous)
        ? previous
        : upsertManagedBlock(previous, claude && !exists ? renderClaudeImport() : block);
      if (next === previous) {
        changes.push({ path, action: "unchanged", tracked: isTracked(repoRoot, target.file) });
        continue;
      }
      await mkdir(dirname(path), { recursive: true });
      await writeFile(path, next, "utf8");
      if (!exists) createdHere.push(target.file);
      changes.push({ path, action: exists ? "updated" : "created", tracked: exists && isTracked(repoRoot, target.file) });
    }
    if (createdHere.length > 0) await excludeLocally(repoRoot, createdHere.map((file) => `/${file}`));
  }
  return changes;
}

export async function unlinkAtlasPointers(repoRoots: readonly string[]): Promise<readonly string[]> {
  const changed: string[] = [];
  for (const repoRoot of repoRoots) {
    for (const target of POINTER_TARGETS) {
      const path = join(repoRoot, target.file);
      if (!existsSync(path)) continue;
      const previous = await readFile(path, "utf8");
      const next = removeManagedBlock(previous);
      if (next !== previous) {
        // Files that only held the Atlas block were created by mr: remove them entirely.
        if (next.trim().length === 0) await rm(path);
        else await writeFile(path, next, "utf8");
        changed.push(path);
      }
    }
  }
  return changed;
}

export interface AtlasPackResult {
  readonly mapPath: string;
  readonly mapChars: number;
  readonly memoryPath?: string;
  readonly pointers: readonly PointerChange[];
  readonly excluded: boolean;
}

export interface WriteAtlasPackInput {
  readonly workspace: WorkspaceProfile;
  readonly graph: AtlasGraph;
  readonly profiles: readonly RepositoryProfile[];
  readonly memory?: readonly { readonly title: string; readonly excerpt: string }[];
  readonly link?: boolean;
}

export async function writeAtlasPack(input: WriteAtlasPackInput): Promise<AtlasPackResult> {
  const root = atlasPackRoot(input.workspace);
  await mkdir(root, { recursive: true });
  const excluded = await excludeLocally(input.workspace.root, ["/.aicontext/"]);
  let memoryPath: string | undefined;
  if (input.memory !== undefined && input.memory.length > 0) {
    memoryPath = join(root, "MEMORY.md");
    await atomicWrite(memoryPath, [
      `# Project memory — ${input.workspace.name}`,
      "",
      "Advisory decisions and conventions recalled from Engram. Code evidence wins when they disagree.",
      "",
      ...input.memory.map((item) => `- **${oneLine(item.title, 120)}** — ${oneLine(item.excerpt, 300)}`),
      "",
    ].join("\n"));
  }
  const head = gitHead(input.workspace.root);
  const map = renderAtlasMap({
    workspace: input.workspace,
    graph: input.graph,
    profiles: input.profiles,
    hasRules: existsSync(join(root, "AGENTS.md")),
    hasMemory: memoryPath !== undefined || existsSync(join(root, "MEMORY.md")),
    ...(head === undefined ? {} : { head }),
  });
  const mapPath = join(root, "MAP.md");
  await atomicWrite(mapPath, map);
  const repoRoots = input.profiles.map((profile) => join(input.workspace.root, profile.root));
  const pointers = input.link === false ? [] : await linkAtlasPointers(input.workspace, repoRoots);
  return { mapPath, mapChars: map.length, ...(memoryPath === undefined ? {} : { memoryPath }), pointers, excluded };
}

// ─── Query (CLI and any shell-capable agent) ────────────────────────────────

export const ATLAS_QUERY_ACTIONS = ["info", "deps", "dependents", "impact", "slice", "tests", "find"] as const;
export type AtlasQueryAction = (typeof ATLAS_QUERY_ACTIONS)[number];

function describe(node: AtlasNode): string {
  return `${node.kind} ${node.name} ${node.filePath}:${String(node.line)}${node.endLine === undefined ? "" : `-${String(node.endLine)}`}`;
}

export function findAtlasNodes(graph: AtlasGraph, name: string): readonly AtlasNode[] {
  const exact = graph.nodes.filter((node) => node.name === name);
  if (exact.length > 0) return exact;
  const lower = name.toLowerCase();
  return graph.nodes.filter((node) => node.name.toLowerCase().includes(lower) || node.filePath.toLowerCase().includes(lower)).slice(0, 20);
}

export interface AtlasQueryDeps {
  readonly dependencies: (graph: AtlasGraph, id: string) => readonly AtlasNode[];
  readonly dependents: (graph: AtlasGraph, id: string) => readonly AtlasNode[];
  readonly impact: (graph: AtlasGraph, id: string, depth: number) => readonly AtlasNode[];
  readonly tests: (graph: AtlasGraph, id: string) => readonly AtlasNode[];
  readonly slice: (node: AtlasNode) => Promise<string>;
}

export async function runAtlasQuery(graph: AtlasGraph, name: string, action: AtlasQueryAction, deps: AtlasQueryDeps, depth = 2): Promise<string> {
  const matches = findAtlasNodes(graph, name);
  if (matches.length === 0) return `No symbol or file matches "${name}". Try \`mr atlas query <part-of-name> find\`.`;
  const exact = matches.every((candidate) => candidate.name === name);
  if (action === "find" || (!exact && matches.length > 1)) {
    const listed = matches.slice(0, 20).map(describe).join("\n");
    return action === "find" ? listed : `"${name}" is ambiguous; pick one exact name:\n${listed}`;
  }
  const [node] = matches;
  if (node === undefined) return `No symbol matches "${name}".`;
  const list = (nodes: readonly AtlasNode[]): string => (nodes.length === 0 ? "(none)" : nodes.slice(0, 60).map(describe).join("\n"));
  if (action === "info") {
    return [
      describe(node),
      ...(node.signature === undefined ? [] : [`signature: ${oneLine(node.signature, 300)}`]),
      `dependents: ${String(node.dependents.length)} · dependencies: ${String(node.dependencies.length)}`,
      ...(matches.length > 1 ? [`also named "${name}": ${matches.slice(1, 6).map(describe).join("; ")}`] : []),
    ].join("\n");
  }
  if (action === "deps") return list(deps.dependencies(graph, node.id));
  if (action === "dependents") return list(deps.dependents(graph, node.id));
  if (action === "impact") return list(deps.impact(graph, node.id, depth));
  if (action === "tests") return list(deps.tests(graph, node.id));
  return `${describe(node)}\n${await deps.slice(node)}`;
}
